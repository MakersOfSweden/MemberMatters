"""Pure accessors for Stripe webhook/API payloads.

Deliberately free of Django models and DB access so `api_admin_tools` can
import these without creating a cycle back through `api_billing.views`.
"""

from datetime import datetime
from datetime import timezone as dt_timezone
from decimal import Decimal

from django.utils import timezone
from django.utils.formats import date_format, number_format
from django.utils.translation import gettext


def invoice_subscription_id(invoice_data):
    # Stripe API 2025-03-31.basil moved Invoice.subscription to
    # Invoice.parent.subscription_details.subscription. Pick whichever the
    # payload actually exposes so a webhook endpoint signed with either API
    # version works. The `in details` check (rather than truthiness) means an
    # explicit `null` in the new schema is honored as "no subscription on this
    # invoice" instead of silently falling back to the legacy field.
    parent = invoice_data.get("parent") or {}
    details = parent.get("subscription_details") or {}
    if "subscription" in details:
        return details["subscription"]
    return invoice_data.get("subscription")


def api_version_major(api_version):
    """The major release a Stripe API version belongs to: "clover" for
    "2025-10-29.clover". None for versions from before Stripe named its
    major releases, such as "2024-04-10"."""
    if not api_version or "." not in api_version:
        return None
    return api_version.rsplit(".", 1)[1]


def subscription_period_end(subscription_data):
    # Stripe API 2025-03-31.basil moved current_period_end from the
    # subscription to each of its items. A membership subscription has a
    # single item, so its period is the subscription's. Older payloads still
    # carry it on the subscription itself.
    items = (subscription_data.get("items") or {}).get("data") or []
    for item in items:
        if item.get("current_period_end") is not None:
            return item["current_period_end"]
    return subscription_data.get("current_period_end")


def invoice_billing_reason(invoice_data):
    return invoice_data.get("billing_reason")


def invoice_will_retry(invoice_data):
    """True when Stripe intends another automatic collection attempt.

    Only meaningful for charge_automatically invoices; send_invoice ones are
    never auto-retried, so this is always False for them.
    """
    return invoice_data.get("next_payment_attempt") is not None


def invoice_is_past_due(invoice_data, now=None):
    """True when the invoice's due date has passed.

    send_invoice invoices carry a due_date; charge_automatically ones do not,
    and are never past due in this sense.
    """
    due_date = invoice_data.get("due_date")
    if due_date is None:
        return False
    reference = now if now is not None else timezone.now()
    return due_date < int(reference.timestamp())


def format_invoice_due_date(invoice_data):
    """Render an invoice due date in the site's timezone and the active
    language, e.g. "14 November 2023", or None.

    Stripe sends unix seconds; rendering them naively would show a date a day
    out for members east of UTC.
    """
    due_date = invoice_data.get("due_date")
    if due_date is None:
        return None

    utc = datetime.fromtimestamp(due_date, tz=dt_timezone.utc)
    return date_format(timezone.localtime(utc), "j F Y")


def format_invoice_amount(invoice_data, prefer="paid"):
    """Render an invoice total in the active language, e.g. "12.50 AUD" or, in
    Swedish, "12,50 AUD".

    Pass prefer="due" for an invoice that has not been paid: Stripe reports
    amount_paid as 0 rather than null on those, so preferring it would quote
    "0.00" for what is still owed.

    Falls back to a bare description when the payload carries no usable
    amount, so an email is still sent rather than one reading "$None".
    """
    fields = (
        ("amount_due", "amount_paid")
        if prefer == "due"
        else ("amount_paid", "amount_due")
    )
    amount = next(
        (invoice_data[f] for f in fields if invoice_data.get(f) is not None),
        None,
    )
    if amount is None:
        return gettext("your membership fee")

    currency = (invoice_data.get("currency") or "").upper()
    formatted = number_format(Decimal(amount) / 100, decimal_pos=2)
    return f"{formatted} {currency}".strip()


def is_subscription_invoice(invoice_data):
    """True when Stripe says this invoice was generated by a subscription.

    Covers subscription_create / subscription_cycle / subscription_update /
    subscription_threshold, and excludes one-off charges ("manual").
    """
    return (invoice_billing_reason(invoice_data) or "").startswith("subscription")
